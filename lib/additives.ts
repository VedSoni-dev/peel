export const ADDITIVES: Record<string, Additive> = Object.fromEntries(
  ROWS.map(([code, name, risk, note]) => [code, { code: code.toUpperCase(), name, risk, note }]),
);

/** "en:e322i" → the table's entry for E322 (sub-numbers like i, ii, iii fold into the main number). */
export function lookupAdditive(tag: string): Additive {
  const raw = tag.replace(/^[a-z]{2}:/, "").toLowerCase();
  const base = raw.replace(/(iii|ii|iv|vi|v|i)$/, "");
  const hit = ADDITIVES[raw] ?? ADDITIVES[base] ?? ADDITIVES[raw.replace(/[a-z]$/, "")];
  return hit ?? { code: base.toUpperCase(), name: "", risk: "none", note: "Not in Peel's table yet, so it costs no points.", unrated: true };
}

/** One entry per additive: "E322" and "E322i" on the same label count once. */
export function uniqueAdditives(tags: string[]): Additive[] {
  const seen = new Map<string, Additive>();
  for (const t of tags) {
    const a = lookupAdditive(t);
    if (!seen.has(a.code)) seen.set(a.code, a);
  }
  return [...seen.values()];
}
